import crypto from "crypto";
import { prisma } from "@/lib/prisma";

export function hashPayload(payload: unknown): string {
  return crypto
    .createHash("sha256")
    .update(JSON.stringify(payload))
    .digest("hex");
}

export interface IdempotencyResult<T> {
  status: number;
  body: T;
  wasReplayed: boolean;
}

/**
 * Wraps a handler with server-side idempotency.
 *
 * Rules:
 * - If the key+userId was never seen: execute handler, store result.
 * - If seen with same requestHash: return stored result (replay).
 * - If seen with different requestHash: return 422.
 * - If expired (>24h): treat as a new operation.
 * - Concurrent requests with the same key: only one creates the record;
 *   the other waits briefly and reads the stored result.
 *
 * The key should be generated by the client per new logical operation
 * and reused only when retrying that exact operation.
 */
export async function withIdempotency<T>(
  key: string,
  userId: string,
  payload: unknown,
  handler: () => Promise<{ status: number; body: T }>
): Promise<IdempotencyResult<T>> {
  const requestHash = hashPayload(payload);
  const expiresAt = new Date(Date.now() + 24 * 60 * 60 * 1000); // 24 hours

  // Check for existing key
  const existing = await prisma.idempotencyKey.findUnique({
    where: { key_userId: { key, userId } },
  });

  if (existing) {
    if (existing.expiresAt < new Date()) {
      // Expired — delete and proceed as new operation
      await prisma.idempotencyKey.delete({ where: { id: existing.id } }).catch(() => {});
    } else if (existing.requestHash !== requestHash) {
      return {
        status: 422,
        body: { error: "IDEMPOTENCY_KEY_REUSED_WITH_DIFFERENT_PAYLOAD" } as T,
        wasReplayed: false,
      };
    } else if (existing.statusCode > 0) {
      // Successful previous response — replay it
      return {
        status: existing.statusCode,
        body: existing.responseBody as T,
        wasReplayed: true,
      };
    } else {
      // statusCode = 0 means a concurrent request is still processing
      await new Promise((r) => setTimeout(r, 100));
      const refreshed = await prisma.idempotencyKey.findUnique({
        where: { key_userId: { key, userId } },
      });
      if (refreshed && refreshed.statusCode > 0) {
        return {
          status: refreshed.statusCode,
          body: refreshed.responseBody as T,
          wasReplayed: true,
        };
      }
      return {
        status: 409,
        body: { error: "CONCURRENT_IDEMPOTENT_REQUEST_RETRY_SHORTLY" } as T,
        wasReplayed: false,
      };
    }
  }

  // Attempt to atomically insert the placeholder row (statusCode = 0 means in-flight)
  try {
    await prisma.idempotencyKey.create({
      data: {
        key,
        userId,
        requestHash,
        statusCode: 0,
        responseBody: {},
        expiresAt,
      },
    });
  } catch {
    // Unique constraint — concurrent request won the insert race
    await new Promise((r) => setTimeout(r, 100));
    const concurrent = await prisma.idempotencyKey.findUnique({
      where: { key_userId: { key, userId } },
    });
    if (concurrent && concurrent.statusCode > 0) {
      return {
        status: concurrent.statusCode,
        body: concurrent.responseBody as T,
        wasReplayed: true,
      };
    }
    return {
      status: 409,
      body: { error: "CONCURRENT_IDEMPOTENT_REQUEST_RETRY_SHORTLY" } as T,
      wasReplayed: false,
    };
  }

  // Execute the handler
  const result = await handler();

  // Store the result
  await prisma.idempotencyKey.update({
    where: { key_userId: { key, userId } },
    data: {
      statusCode: result.status,
      responseBody: result.body as any,
    },
  });

  return { ...result, wasReplayed: false };
}
